import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { assemblyGlb } from "../dist/glb.js";
import { ASSET_PACK, packDimensions } from "../dist/pack.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const assetDir = resolve(root, "apps/web/public/assets");
mkdirSync(assetDir, { recursive: true });

const records = ASSET_PACK.map((item) => {
  writeFileSync(resolve(assetDir, item.file), assemblyGlb(item.parts));
  return {
    id: item.id,
    name: item.name,
    category: item.category,
    dimensions: packDimensions(item.parts),
    licence: "Apache-2.0",
    attribution: "Apache-2.0. Generated by OpenVenue, not a third-party scan.",
    version: "1",
    tags: item.tags,
    thumbnail: swatch(item.swatch),
    url: `/assets/${item.file}`,
  };
});

const source = `// Generated by packages/renderer-3d/scripts/write-pack.mjs. Do not edit.
import type { AssetRecord } from "./catalogue";

export const CATALOGUE_DATA: readonly AssetRecord[] = ${JSON.stringify(records, null, 2)};
`;
writeFileSync(resolve(root, "apps/web/src/assets/catalogue.data.ts"), source);

function swatch(color) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><rect width="64" height="64" rx="8" fill="${color}"/></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}
